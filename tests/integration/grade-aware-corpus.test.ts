import { readFileSync } from "node:fs";
import { eq } from "drizzle-orm";
import { expect, test } from "vitest";
import { withDatabaseRollback } from "../helpers/database";
import { user as authUsers } from "@/modules/auth/schema";
import { children, families, guardians } from "@/modules/families/schema";
import { learningCards } from "@/modules/learning-content/schema";
import { applySeedContents } from "@/modules/learning-content/seed-service";
import { createLearningContentService } from "@/modules/learning-content/service";
import { createDictationTaskService } from "@/modules/dictation/task-service";
import { createTaskBuilderQueryService } from "@/modules/dictation/task-builder-query";
import { learningTasks, learningTaskItems } from "@/modules/dictation/task-schema";
import { createReviewService } from "@/modules/review/service";
import { childCardStates, reviewEvents } from "@/modules/review/db-schema";
import type { ChineseContentRequirements } from "@/modules/learning-content/content-audit";

const load = (path: string) => JSON.parse(readFileSync(path, "utf8"));
const replacements = load("content/official-chinese-replacements.json") as { replacements: Array<{ previousKey: string; previousAnswer: string; previousBroadcastText: string; previousPinyinText: string }> };

test("旧单字的卡片、任务和复习历史不改写，但不能再进入新任务或自动复习", async () => {
  await withDatabaseRollback(async tx => {
    const change = replacements.replacements.find(row => row.previousKey.includes("-g2-v1-") && row.previousAnswer === "宽")!;
    const [oldCard] = await tx.insert(learningCards).values({ subject: "chinese", source: "builtin", builtinKey: change.previousKey, answerText: change.previousAnswer, broadcastText: change.previousBroadcastText, pinyinText: change.previousPinyinText, curriculumSource: "writing_practice" }).returning();
    const authUserId = `grade-aware-${crypto.randomUUID()}`;
    await tx.insert(authUsers).values({ id: authUserId, name: "历史记录测试", email: `${authUserId}@example.test` });
    const [family] = await tx.insert(families).values({ name: "分级词库历史家庭" }).returning();
    const [guardian] = await tx.insert(guardians).values({ familyId: family.id, authUserId }).returning();
    const [child] = await tx.insert(children).values({ familyId: family.id, nickname: "孩子", avatarKey: "child-1", grade: 2 }).returning();
    const actor = { role: "guardian" as const, familyId: family.id, guardianId: guardian.id };
    const [personal] = await tx.insert(learningCards).values({ familyId: family.id, subject: "chinese", answerText: "自建词", broadcastText: "自建词", source: "manual" }).returning();
    const [oldTask] = await tx.insert(learningTasks).values({ familyId: family.id, childId: child.id, guardianId: guardian.id, commandId: crypto.randomUUID(), inputFingerprint: "old-character-history", mode: "continuous_batch", taskOrder: "source", intervalSeconds: 5, repeatCount: 1, speechRate: "1", allowManualReplay: true, maxReviewCards: 0 }).returning();
    await tx.insert(learningTaskItems).values({ taskId: oldTask.id, familyId: family.id, childId: child.id, cardId: oldCard.id, cardFamilyId: null, kind: "new", position: 0, ttsDedupeKey: "old-character-history-audio" });
    const review = createReviewService(tx);
    await review.recordFirstResult({ familyId: family.id, childId: child.id }, { cardId: oldCard.id, commandId: crypto.randomUUID(), correct: true, reviewedAt: new Date("2026-11-01T00:00:00Z"), eventType: "new_first" });
    const statesBefore = await tx.select().from(childCardStates).where(eq(childCardStates.cardId, oldCard.id));
    const eventsBefore = await tx.select().from(reviewEvents).where(eq(reviewEvents.cardId, oldCard.id));
    const seed = load("content/seed/chinese-official-grade2-volume1.json");
    const ref = load("content/reference/chinese-official-grade2-volume1.json") as ChineseContentRequirements;
    await applySeedContents(tx, [seed], [ref]);
    expect((await tx.select().from(learningCards).where(eq(learningCards.id, oldCard.id)))[0]).toEqual(oldCard);
    expect(await tx.select().from(childCardStates).where(eq(childCardStates.cardId, oldCard.id))).toEqual(statesBefore);
    expect(await tx.select().from(reviewEvents).where(eq(reviewEvents.cardId, oldCard.id))).toEqual(eventsBefore);
    const service = createDictationTaskService(tx);
    const task = await service.getTask(actor, oldTask.id);
    expect(task.items[0]!.cardId).toBe(oldCard.id);
    expect(task.items[0]!.ttsDedupeKey).toBe("old-character-history-audio");
    const visible = await createLearningContentService(tx).listCards(actor, {});
    expect(visible.some(card => card.id === oldCard.id)).toBe(false);
    expect(visible.some(card => card.id === personal.id)).toBe(true);
    const builder = await createTaskBuilderQueryService(tx).getTaskBuilderData(actor, new Date("2026-12-01T00:00:00Z"));
    expect(builder.cards.some(card => card.id === oldCard.id)).toBe(false);
    expect(builder.children[0]!.dueCount).toBe(0);
    expect(await review.countDueCards({ familyId: family.id, childId: child.id }, new Date("2026-12-01T00:00:00Z"))).toBe(0);
    expect(await review.getDueCards({ familyId: family.id, childId: child.id }, new Date("2026-12-01T00:00:00Z"), 10)).toEqual([]);
    const settings = { childId: child.id, subject: "chinese" as const, mode: "continuous_batch" as const, order: "source" as const, intervalSeconds: 5, repeatCount: 1 as const, speechRate: 1, allowManualReplay: true };
    await expect(service.buildDailyTask(actor, { ...settings, newCardIds: [oldCard.id], commandId: crypto.randomUUID(), maxReviewCards: 0 })).rejects.toThrow("TASK_CARD_NOT_FOUND");
    await expect(service.buildTaskBatch(actor, { ...settings, sectionIds: [], extraCardIds: [oldCard.id], commandId: crypto.randomUUID() })).rejects.toThrow("TASK_CARD_NOT_FOUND");
  });
}, 60000);
